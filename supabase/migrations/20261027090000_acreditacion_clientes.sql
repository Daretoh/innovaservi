-- ============================================================
-- Documentos estándar y acreditación por cliente (2026-10-27). Idempotente.
-- doc_tipos            catálogo de documentos del trabajador (antes RRHH_TIPOS / CAP_TIPOS / BUK_TIPOS en el código).
--                      fuente 'buk' = se firma y guarda en Buk (no se sube aquí). cliente_id = documento propio de ese cliente.
-- cliente_requisitos   qué pide cada cliente (y lugar) para validar a la empresa y a cada trabajador.
-- cliente_validaciones quién está validado (marca manual, con vigencia) en cada cliente / lugar.
-- En ISgestión: rrhh_tipos_doc, acr_requisitos, acr_validaciones.
-- ============================================================

create table if not exists public.doc_tipos (
  slug        text primary key check (slug ~ '^[a-z][a-z0-9_]*$'),
  nombre      text not null check (length(trim(nombre)) > 0),
  corto       text,
  categoria   text not null default 'documento' check (categoria in ('documento','capacitacion')),
  fuente      text not null default 'ig' check (fuente in ('ig','buk')),
  estandar    boolean not null default true,      -- set base: cuenta en el % al día
  vence       boolean not null default false,
  dias_aviso  int not null default 30 check (dias_aviso between 0 and 365),
  permite_na  boolean not null default false,
  cliente_id  bigint references public.clientes(id) on delete cascade,
  orden       int not null default 0,
  activo      boolean not null default true,
  autor       text,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz
);

create table if not exists public.cliente_requisitos (
  id          bigint generated by default as identity primary key,
  cliente_id  bigint not null references public.clientes(id) on delete cascade,
  sitio       text,                                   -- null = todos los lugares del cliente
  ambito      text not null check (ambito in ('empresa','trabajador')),
  tipo        text not null,                          -- slug de doc_tipos (trabajador) o tipo de empresa_docs (empresa)
  nota        text,
  orden       int not null default 0,
  autor       text,
  created_at  timestamptz not null default now()
);
create unique index if not exists cliente_requisitos_uq on public.cliente_requisitos (cliente_id, coalesce(sitio,''), ambito, tipo);

create table if not exists public.cliente_validaciones (
  id            bigint generated by default as identity primary key,
  cliente_id    bigint not null references public.clientes(id) on delete cascade,
  trabajador_id bigint not null references public.trabajadores(id) on delete cascade,
  sitio         text,                                 -- null = todos los lugares
  estado        text not null default 'validado' check (estado in ('enviado','validado','rechazado')),
  desde         date,
  hasta         date,                                 -- vigencia de la acreditación (null = sin vencimiento)
  nota          text,
  autor         text,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz
);
create unique index if not exists cliente_validaciones_uq on public.cliente_validaciones (cliente_id, trabajador_id, coalesce(sitio,''));

alter table public.doc_tipos enable row level security;
alter table public.cliente_requisitos enable row level security;
alter table public.cliente_validaciones enable row level security;

drop policy if exists doc_tipos_sel on public.doc_tipos;
create policy doc_tipos_sel on public.doc_tipos for select to authenticated using ((select public.ig_activo()));
drop policy if exists doc_tipos_wr on public.doc_tipos;
create policy doc_tipos_wr on public.doc_tipos for all to authenticated
  using ((select public.ig_algun(2,'documentacion','trabajadores'))) with check ((select public.ig_algun(2,'documentacion','trabajadores')));

drop policy if exists cliente_requisitos_sel on public.cliente_requisitos;
create policy cliente_requisitos_sel on public.cliente_requisitos for select to authenticated using ((select public.ig_activo()));
drop policy if exists cliente_requisitos_wr on public.cliente_requisitos;
create policy cliente_requisitos_wr on public.cliente_requisitos for all to authenticated
  using ((select public.ig_algun(2,'clientes','documentacion'))) with check ((select public.ig_algun(2,'clientes','documentacion')));

drop policy if exists cliente_validaciones_sel on public.cliente_validaciones;
create policy cliente_validaciones_sel on public.cliente_validaciones for select to authenticated
  using ((select public.ig_algun(1,'clientes','documentacion','trabajadores','planificacion','calendario')));
drop policy if exists cliente_validaciones_wr on public.cliente_validaciones;
create policy cliente_validaciones_wr on public.cliente_validaciones for all to authenticated
  using ((select public.ig_algun(2,'clientes','documentacion'))) with check ((select public.ig_algun(2,'clientes','documentacion')));

